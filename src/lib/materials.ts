export function materialById(id: string | undefined): Material | undefined {
  return id ? MATERIALS.find((m) => m.id === id) : undefined;
}

export function categoryInfo(id: Category) {
  return CATEGORIES.find((c) => c.id === id)!;
}

/** How much of a material a swatch should show (cm), so a large repeat is seen whole. */
export function swatchSizeCm(m: Material): number {
  if (m.category === "flooring") return 90;
  return Math.max(45, Math.round(m.repeatCm * 1.5));
}
